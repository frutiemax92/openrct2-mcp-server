const RIDES: Record<string, number> = { P: 12, K: 9, M: 10 };

export function bwdTile(x: number, y: number): RegionTile {
    const c = ROWS[y]?.[x - 50] ?? ".";
    const t: RegionTile = { h: 7, s: 0, w: 0, t: 0, o: 1 };
    if (c === "~") Object.assign(t, { h: 4, w: 6 });
    else if (c === "^") Object.assign(t, { h: 6, s: 1 });
    else if (c === "#") t.p = [{ l: 7, q: 0, e: 15, sd: -1, r: -1, a: -1 }] as never;
    else if (c === "=") t.p = [{ l: 7, q: 1, e: 15, sd: -1, r: -1, a: -1 }] as never;
    else if (c === "T") t.sc = 1;
    else if (RIDES[c] !== undefined) Object.assign(t, { r: [RIDES[c]], rh: 30, ri: [[7, 30, RIDES[c]]] });
    return t;
}

export const bwdEnv: T.TrackEnv = { get: bwdTile, rideId: 5, sandbox: true, mapSize: { x: 154, y: 154 } };
